'use strict';
// Train. T слева, CT справа. A — большой двор с вагонами по центру, B — внизу справа, тоже с вагонами.
const { MapBuilder } = require('../lib');

module.exports = function train() {
  const m = new MapBuilder('train', 6006);

  /* ---------- T-спавн ---------- */
  m.floor(4, 54, 20, 94, 0);
  m.spawn('T', 6, 60, 17, 88);

  /* ---------- Айви (T → A с севера-запада) ---------- */
  m.floor(10, 20, 18, 53, 0);
  m.floor(19, 20, 36, 27, 0);
  m.crate(13, 34, 14, 35, true).crate(22, 22, 22, 23, false);

  /* ---------- T-коннектор и «поп-дог» (T → A с юга) ---------- */
  m.floor(21, 60, 40, 67, 0);
  m.floor(34, 51, 40, 59, 0);
  m.crate(26, 61, 27, 62, true);

  /* ---------- A: двор с вагонами ---------- */
  m.floor(37, 20, 84, 50, 0);
  m.site('A', 37, 20, 84, 50);
  // вагоны по путям (вдоль x), между ними проходы
  m.solid(44, 25, 57, 27, 'W').solid(61, 25, 76, 27, 'W');
  m.solid(41, 32, 53, 34, 'W').solid(57, 32, 72, 34, 'W');
  m.solid(46, 40, 62, 42, 'W').solid(66, 40, 79, 42, 'W');
  m.crate(78, 23, 79, 24, true).crate(39, 46, 40, 47, true).crate(81, 46, 81, 46, false);
  // лестничная (ladder room) к CT
  m.floor(70, 12, 78, 19, 0);

  /* ---------- Нижний и верхний холлы B ---------- */
  m.floor(21, 76, 56, 82, 0);                 // верхний холл
  m.floor(21, 86, 56, 94, -1);                // нижний холл
  m.ramp(21, 83, 26, 85, 'z', 0, -1);
  m.floor(41, 68, 47, 75, 0);                 // связка с поп-догом

  /* ---------- B ---------- */
  m.floor(57, 64, 95, 94, 0);
  m.ramp(57, 86, 60, 94, 'x', -1, 0);
  m.site('B', 57, 64, 95, 94);
  m.solid(62, 71, 76, 73, 'W').solid(80, 71, 92, 73, 'W');
  m.solid(64, 82, 82, 84, 'W');
  m.crate(87, 88, 88, 89, true).crate(60, 66, 60, 66, false);

  /* ---------- CT ---------- */
  m.floor(85, 4, 96, 63, 0);
  m.spawn('CT', 87, 22, 95, 46);
  m.floor(70, 4, 84, 11, 0);
  m.floor(79, 51, 84, 63, 0);                 // CT → B (Z-образный проход у B)
  // стены между CT и точками: только проходы, а не открытая сторона
  m.wall(85, 20, 85, 50, 8).floor(85, 33, 85, 37, 0);
  m.wall(85, 63, 96, 63, 8).floor(88, 63, 91, 63, 0);

  for (let i = 0; i < 100; i++) { m.wallH(i, 0, i, 1, 11); m.wallH(i, 98, i, 99, 11); m.wallH(0, i, 1, i, 11); m.wallH(98, i, 99, i, 11); }

  /* ---------- Декорации ---------- */
  const wagon = (x0, z0, x1, c) => { m.add('wagon', (x0 + x1 + 1) / 2, 0, z0 + 1.5, x1 - x0 + 1, 0, c); };
  wagon(44, 25, 57, 0x5a3a2a); wagon(61, 25, 76, 0x3f5c45);
  wagon(41, 32, 53, 0x2f4f7a); wagon(57, 32, 72, 0x6a2e2a);
  wagon(46, 40, 62, 0x7a6a3a); wagon(66, 40, 79, 0x3f5c45);
  wagon(62, 71, 76, 0x6a2e2a); wagon(80, 71, 92, 0x2f4f7a);
  wagon(64, 82, 82, 0x5a3a2a);
  for (const z of [26.5, 33.5, 41.5]) m.add('track', 37, z, 85, z, 0);
  for (const z of [72.5, 83.5]) m.add('track', 57, z, 96, z, 0);
  m.span(21, 76, 56, 82, 4.6, 0.5, 'wall');    // крыша верхнего холла
  m.span(21, 86, 56, 94, 3.4, 0.5, 'wall');    // крыша нижнего холла
  m.span(70, 12, 78, 19, 5.0, 0.4, 'wall');    // лестничная
  // плющ (зелёные пятна на стенах айви)
  for (const [x, z] of [[9, 26], [9, 33], [9, 41], [19, 47]]) m.add('bush', x + 0.8, 0, z + 0.5, 1.2);
  m.winRow('e', 9, 22, 52, 3.8, 6, 1.2, 1.4, 0);
  m.winRow('s', 19, 38, 82, 5.0, 6, 1.4, 1.6, 0);
  m.winRow('n', 95, 58, 94, 4.2, 6, 1.4, 1.6, 0);
  m.winRow('w', 97, 6, 62, 4.0, 7, 1.2, 1.4, 0);
  for (const [x, z] of [[36, 21], [84, 21], [36, 49], [84, 49], [58, 65], [94, 65], [58, 93], [94, 93]]) m.add('lamp', x + 0.5, 0, z + 0.5);
  m.add('wire', 37, 9, 30, 84, 9, 30).add('wire', 37, 9, 45, 84, 9, 45).add('wire', 57, 9, 78, 96, 9, 78);
  for (const [x, z] of [[5, 55], [20, 21], [40, 66], [56, 77], [95, 62], [85, 5]]) { m.add('barrel', x + 0.5, m.fl(x, z), z + 0.5); m.solid(x, z, x, z, 'o'); }
  m.sign(36, 23, 'w', 'A →', 2.6, 0.5);
  m.sign(20, 66, 'e', '← B', 2.6);
  m.sign(40, 59, 'e', 'A ↑', 2.4);
  return m;
};
