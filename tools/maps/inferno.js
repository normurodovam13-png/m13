'use strict';
// Inferno. Север — верх. T-спавн внизу слева, B наверху (через банан), A справа, CT вверху справа.
const { MapBuilder } = require('../lib');

module.exports = function inferno() {
  const m = new MapBuilder('inferno', 4004);

  /* ---------- T-спавн ---------- */
  m.floor(5, 76, 32, 95, 0);
  m.spawn('T', 9, 82, 27, 92);

  /* ---------- Банан (T → B) ---------- */
  m.ramp(18, 56, 26, 75, 'z', 1, 0);         // нижний банан
  m.ramp(20, 30, 28, 55, 'z', 2, 1);         // банан
  m.floor(24, 23, 32, 29, 2);                // верх банана у B
  m.crate(25, 40, 25, 41, false).crate(23, 32, 24, 33, true);   // мешки и ящики на банане
  m.wall(21, 47, 22, 50, 3.0);               // клумба-стенка посреди банана

  /* ---------- B ---------- */
  m.floor(12, 4, 48, 22, 2);
  m.site('B', 12, 4, 48, 22);
  m.solid(28, 11, 31, 14, 'o');              // фонтан
  m.crate(14, 5, 16, 7, true).crate(17, 5, 17, 5, false);       // «гробы»
  m.crate(40, 16, 41, 18, true);              // новый ящик
  m.crate(13, 18, 14, 19, false);             // тёмный угол
  m.floor(49, 7, 56, 14, 2);                  // церковь → CT

  /* ---------- Мид ---------- */
  m.ramp(33, 80, 46, 88, 'x', 0, 0.5);        // второй мид
  m.floor(46, 50, 56, 88, 0.5);
  m.ramp(46, 50, 56, 56, 'z', 1, 0.5);
  m.floor(44, 42, 62, 49, 1);                 // топ-мид
  m.crate(48, 64, 49, 65, true).crate(55, 72, 55, 72, false);
  // арка → CT и библиотека
  m.floor(63, 33, 70, 45, 1);
  m.ramp(63, 27, 70, 32, 'z', 2, 1);
  // шорт к A
  m.floor(63, 46, 71, 53, 1);

  /* ---------- Апартаменты (T → балкон над A) ---------- */
  m.ramp(33, 89, 50, 94, 'x', 0, 3);          // лестница в апартаменты
  m.floor(51, 88, 78, 94, 3);
  m.floor(72, 62, 78, 87, 3);                 // бойлер
  m.floor(72, 57, 84, 61, 3);                 // балкон
  m.ramp(79, 57, 84, 58, 'x', 3, 3);

  /* ---------- A ---------- */
  m.floor(72, 28, 96, 56, 1);
  m.site('A', 72, 28, 96, 56);
  m.ramp(85, 57, 96, 60, 'z', 1, -0.5);       // спуск в яму
  m.floor(85, 61, 96, 72, -1);                // яма
  m.crate(80, 38, 81, 39, true).crate(82, 38, 82, 38, false);   // ящик на A
  m.crate(90, 30, 91, 31, true);
  m.solid(75, 50, 78, 51, 'q');               // повозка
  m.crate(93, 66, 94, 67, true);
  // переход A → балкон: ступени (с балкона можно спрыгнуть)
  m.ramp(72, 53, 77, 56, 'z', 3, 1.5);

  /* ---------- CT ---------- */
  m.floor(57, 4, 94, 26, 2);
  m.spawn('CT', 62, 8, 88, 20);
  m.floor(88, 27, 91, 27, 1.5);             // узкий проход CT → A

  // внешние стены выше
  for (let i = 0; i < 100; i++) { m.wallH(i, 0, i, 1, 10); m.wallH(i, 98, i, 99, 10); m.wallH(0, i, 1, i, 10); m.wallH(98, i, 99, i, 10); }

  /* ---------- Декорации ---------- */
  m.span(51, 87, 78, 95, 6.6, 0.5, 'wall');   // крыша апартаментов
  m.span(71, 62, 79, 87, 6.6, 0.5, 'wall');
  m.span(63, 33, 70, 37, 5.2, 1.2, 'wall');   // арка
  m.span(49, 7, 56, 14, 6.0, 0.5, 'wall');    // свод церкви
  m.add('rail', 78, 3, 57.05, 84.9, 3, 57.05, 1.0).add('rail', 84.95, 3, 57, 84.95, 3, 62, 1.0);
  m.add('fountain', 30, 2, 13, 2.1);
  // деревья и кусты
  for (const [x, z] of [[19, 77], [30, 95], [27, 33], [45, 5], [64, 24], [95, 29], [50, 40], [17, 60]]) { m.add('tree', x + 0.5, m.fl(x, z), z + 0.5, 6 + (x % 3)); m.solid(x, z, x, z, 'O'); }
  for (const [x, z, s] of [[22, 44, 1.1], [26, 52, 0.9], [44, 21, 1.0], [72, 29, 0.9], [96, 50, 1.1], [57, 25, 1.0], [6, 77, 1.0]]) m.add('bush', x + 0.5, m.fl(x, z), z + 0.5, s);
  for (const [x, z] of [[31, 76], [47, 86], [86, 72], [12, 22], [70, 45], [94, 4]]) { m.add('barrel', x + 0.5, m.fl(x, z), z + 0.5); m.solid(x, z, x, z, 'o'); }
  m.add('car', 76.5, 1, 50.9, 0.05, 0x6b4a2b);
  // окна со ставнями (терракота, зелёные и синие ставни)
  m.winRow('s', 3, 13, 47, 4.4, 5, 1.0, 1.4, 0x3f6b3a);
  m.winRow('n', 96, 6, 31, 3.6, 5, 1.0, 1.4, 0x2f5f8a);
  m.winRow('e', 19, 31, 54, 3.8, 5, 0.9, 1.3, 0x3f6b3a);
  m.winRow('w', 29, 31, 54, 3.8, 5, 0.9, 1.3, 0x8a3b2c);
  m.winRow('w', 97, 30, 55, 3.8, 5, 1.0, 1.4, 0x2f5f8a);
  m.winRow('s', 3, 58, 93, 4.4, 5, 1.0, 1.4, 0x3f6b3a);
  m.winRow('w', 57, 52, 86, 3.2, 5, 1.0, 1.3, 0x8a3b2c);
  // навесы, провода, фонари
  m.awning(45, 70, 'e', 3.2, 4, 1.4, 0x8a3b2c);
  m.awning(11, 12, 'e', 4.4, 4, 1.4, 0x3f6b3a);
  m.add('wire', 20, 7, 40, 29, 7, 40).add('wire', 46, 6.5, 70, 57, 6.5, 70).add('wire', 72, 7, 45, 97, 7, 45);
  for (const [x, z] of [[29, 26], [62, 47], [88, 26], [33, 78]]) m.add('lamp', x + 0.5, m.fl(x, z), z + 0.5);
  // надписи
  m.sign(17, 60, 'e', 'B ↑', 2.4);
  m.sign(62, 49, 's', 'A →', 2.8);
  m.sign(71, 88, 'n', '← A', 4.6);
  return m;
};
