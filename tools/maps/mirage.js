'use strict';
// Mirage. Север — верх. T-спавн справа, CT слева; A внизу слева, B вверху слева, мид по центру.
const { MapBuilder } = require('../lib');

module.exports = function mirage() {
  const m = new MapBuilder('mirage', 3003);

  /* ---------- T-спавн ---------- */
  m.floor(80, 38, 96, 64, 3);
  m.spawn('T', 84, 43, 94, 59);

  /* ---------- Мид ---------- */
  m.ramp(64, 44, 79, 52, 'x', 1.5, 3);    // топ-мид: спуск от спавна
  m.floor(35, 42, 63, 54, 1);
  m.ramp(55, 42, 63, 54, 'x', 1, 1.5);
  // окно (комната снайпера CT над мидом)
  m.floor(27, 44, 32, 52, 3.5);
  m.wall(33, 42, 34, 54, 7).wall(33, 46, 34, 50, 4.6);   // проём окна: низкий подоконник
  m.ramp(22, 46, 26, 50, 'x', 1, 3);
  m.crate(40, 50, 41, 51, true).crate(52, 43, 52, 44, false);

  /* ---------- Коннектор и джунгли (мид → A) ---------- */
  m.floor(40, 55, 45, 63, 1);
  m.ramp(40, 59, 45, 63, 'z', 1, 2);
  m.floor(28, 62, 45, 68, 2);              // джунгли
  m.ramp(28, 62, 33, 68, 'x', 1, 2);       // лестница из джунглей на A
  m.crate(36, 64, 37, 65, false);

  /* ---------- Шорт (мид → B) ---------- */
  m.floor(43, 30, 48, 41, 1.5);
  m.ramp(43, 38, 48, 41, 'z', 1.5, 1);
  m.floor(33, 24, 48, 30, 1.5);

  /* ---------- A ---------- */
  m.floor(6, 64, 27, 90, 1);
  m.site('A', 6, 64, 27, 90);
  m.crate(15, 76, 16, 77, true).crate(17, 76, 17, 76, true).crate(15, 78, 15, 78, false); // тройной ящик
  m.crate(22, 71, 23, 72, true);                                                         // файрбокс
  m.crate(10, 80, 11, 81, false);
  m.crate(24, 84, 25, 85, true);
  m.solid(6, 64, 8, 66, 'Q');               // будка с билетами (у CT)
  // рампа A от T
  m.ramp(66, 64, 80, 71, 'x', 1.5, 3);
  m.floor(66, 64, 72, 78, 1.5);
  m.ramp(44, 71, 65, 78, 'x', 1, 1.5);
  m.floor(28, 71, 44, 79, 1);
  m.crate(38, 72, 39, 73, true).crate(40, 77, 40, 78, false);   // «тетрис»
  // палас: от T вниз, коридор на запад, балкон над A
  m.floor(74, 65, 80, 94, 3);
  m.ramp(74, 65, 80, 72, 'z', 3, 3);
  m.floor(36, 87, 79, 93, 3);
  m.floor(28, 84, 35, 93, 3.5);            // балкон паласа
  m.ramp(26, 84, 27, 90, 'x', 1.5, 3).ramp(24, 84, 25, 90, 'x', 1, 1.5);

  /* ---------- CT ---------- */
  m.floor(5, 42, 21, 62, 1);
  m.floor(22, 51, 24, 62, 1);
  m.spawn('CT', 8, 46, 19, 58);
  m.floor(25, 56, 27, 63, 1);              // CT → джунгли / A

  /* ---------- B ---------- */
  m.floor(5, 5, 32, 33, 1);
  m.site('B', 5, 5, 32, 33);
  m.solid(13, 10, 17, 11, 'q');            // фургон
  m.crate(24, 12, 25, 13, true).crate(9, 22, 10, 23, true).crate(20, 24, 20, 24, false);
  m.floor(6, 34, 11, 41, 1);               // кухня → CT
  m.floor(14, 34, 22, 41, 1);              // маркет
  m.wall(14, 37, 22, 37, 7).floor(17, 37, 18, 37, 1);  // дверь маркета
  // апартаменты: от T на север, затем коридор на запад, лестница вниз на B
  m.floor(84, 18, 92, 37, 3);
  m.ramp(84, 18, 92, 22, 'z', 4, 3);
  m.floor(42, 12, 92, 18, 4);
  m.ramp(33, 12, 41, 18, 'x', 1, 4);

  // внешние стены выше
  for (let i = 0; i < 100; i++) { m.wallH(i, 0, i, 1, 10); m.wallH(i, 98, i, 99, 10); m.wallH(0, i, 1, i, 10); m.wallH(98, i, 99, i, 10); }

  /* ---------- Декорации ---------- */
  m.span(42, 11, 92, 19, 7.3, 0.5, 'wall');      // крыша апартаментов
  m.span(36, 86, 79, 94, 6.4, 0.5, 'wall');      // крыша паласа
  m.span(73, 64, 81, 86, 6.4, 0.5, 'wall');
  m.span(40, 58, 45, 63, 4.6, 0.5, 'wall');      // крыша коннектора
  m.span(14, 34, 22, 41, 4.4, 0.5, 'wall');      // крыша маркета
  m.span(33, 46, 34, 50, 6.4, 0.6, 'trim');      // перемычка окна
  // колонны и арки паласа
  for (const z of [84.3, 88.5, 92.7]) m.box(28.3, 3.5, z, 0.55, 2.9, 0.55, 'trim');
  m.span(28, 84, 28, 93, 6.4, 0.6, 'trim');
  m.span(28, 84, 35, 93, 7.0, 0.4, 'wall');
  m.add('rail', 28.1, 3.5, 85, 28.1, 3.5, 88, 0.9).add('rail', 28.1, 3.5, 89, 28.1, 3.5, 92.2, 0.9);
  // навесы
  m.awning(63, 54, 'n', 3.6, 3, 1.4, 0xb5452f, 0.5);
  m.awning(48, 41, 'n', 3.4, 4, 1.4, 0x2f6fa5);
  m.awning(26, 63, 'n', 3.4, 3, 1.3, 0xc78f2d);
  m.awning(4, 50, 'e', 3.2, 5, 1.5, 0x6a8d3c);
  m.awning(32, 17, 'e', 3.4, 4, 1.5, 0xb5452f);
  // окна
  m.winRow('s', 41, 36, 62, 3.6, 4, 1.1, 1.4, 0x3d6e8e);
  m.winRow('n', 55, 47, 62, 3.6, 5, 1.0, 1.3, 0x6b4a2b);
  m.winRow('w', 97, 40, 62, 5.4, 5, 1.1, 1.4, 0x3d6e8e);
  m.winRow('s', 4, 8, 30, 3.6, 5, 1.1, 1.4, 0x7a5a2b);
  m.winRow('n', 91, 8, 26, 3.6, 5, 1.1, 1.4, 0x3d6e8e);
  m.winRow('e', 4, 44, 60, 3.4, 5, 1.0, 1.3, 0x6b4a2b);
  // пальмы, кусты, бочки, фонари
  for (const [x, z] of [[82, 62], [94, 40], [6, 61], [30, 33], [7, 88], [44, 70]]) { m.add('palm', x + 0.5, m.fl(x, z), z + 0.5, 5 + (x % 3)); m.solid(x, z, x, z, 'O'); }
  for (const [x, z] of [[96, 63], [62, 43], [5, 5], [26, 63], [27, 89], [44, 55], [92, 37]]) { m.add('barrel', x + 0.5, m.fl(x, z), z + 0.5); m.solid(x, z, x, z, 'o'); }
  for (const [x, z] of [[66, 51], [20, 60], [30, 26], [88, 18]]) m.add('lamp', x + 0.5, m.fl(x, z), z + 0.5);
  m.add('car', 15.5, 1, 10.9, 0, 0xd8d2c0);
  m.add('wire', 35, 7, 48, 63, 7, 48).add('wire', 6, 7, 70, 27, 7, 70);
  // надписи
  m.sign(33, 52, 'e', 'A →', 2.4);
  m.sign(42, 41, 's', '↑ B', 2.6);
  m.sign(65, 70, 's', '← A', 2.8);
  m.sign(93, 37, 'w', 'B ↑', 4.4);
  return m;
};
