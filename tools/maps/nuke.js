'use strict';
// Nuke. T слева, CT справа, двор с контейнерами сверху, A — в здании по центру, нижняя B под ней (сдвинута на юг).
const { MapBuilder } = require('../lib');

module.exports = function nuke() {
  const m = new MapBuilder('nuke', 5005);

  /* ---------- T-спавн и крыша T ---------- */
  m.floor(4, 34, 22, 72, 0);
  m.spawn('T', 7, 40, 19, 66);

  /* ---------- Двор (outside) ---------- */
  m.floor(4, 4, 74, 30, 0);
  m.floor(10, 31, 22, 33, 0);
  m.solid(28, 9, 33, 10, 'Q').solid(28, 11, 33, 12, 'Q');   // контейнеры
  m.solid(40, 18, 41, 25, 'Q');
  m.solid(52, 6, 57, 7, 'Q');
  m.solid(62, 12, 67, 21, 'O');                            // силосы
  m.crate(18, 24, 19, 25, true).crate(47, 27, 48, 28, false);

  /* ---------- Лобби и хат ---------- */
  m.floor(23, 40, 44, 58, 0);                  // лобби
  m.floor(23, 34, 28, 39, 0);                  // из лобби во двор («скрипучая»)
  m.floor(44, 38, 49, 44, 0);                  // хат → A
  m.crate(40, 52, 41, 53, true);

  /* ---------- A (внутри здания) ---------- */
  m.floor(50, 33, 80, 60, 0);
  m.site('A', 50, 33, 80, 60);
  m.crate(62, 44, 63, 45, true).crate(64, 44, 64, 44, false);   // «жёлтый» ящик
  m.solid(70, 36, 75, 37, 'Q');                                 // контейнер у мини
  m.crate(55, 55, 56, 56, true);
  m.floor(81, 44, 85, 50, 0);                  // проход A → CT («мини»)
  m.floor(66, 31, 72, 32, 0);                  // проход A → двор (главные ворота)

  /* ---------- Рампа и нижняя B ---------- */
  m.ramp(29, 59, 38, 80, 'z', 0, -4);          // рампа (из лобби вниз)
  m.floor(39, 72, 48, 80, -4);
  m.floor(49, 66, 80, 94, -4);
  m.site('B', 49, 66, 80, 94);
  m.crate(58, 74, 59, 75, true).crate(68, 84, 69, 85, true).crate(73, 72, 73, 72, false);
  m.solid(62, 88, 66, 89, 'Q');
  // вентиляция: с A падаем вниз на B (обратно нельзя)
  m.floor(76, 61, 78, 65, 0);
  // секрет: от B к CT и двору вокруг
  m.ramp(81, 70, 86, 90, 'z', 0, -4);
  m.floor(81, 91, 94, 94, -4).ramp(87, 70, 94, 94, 'z', 0, -4);
  m.floor(81, 61, 94, 69, 0);

  /* ---------- CT ---------- */
  m.floor(86, 4, 96, 69, 0);
  m.spawn('CT', 88, 30, 95, 52);
  m.floor(75, 4, 85, 12, 0);                   // гараж → двор

  // высокие стены здания реактора и внешние стены
  m.wallH(45, 30, 49, 37, 12).wallH(81, 30, 85, 43, 12).wallH(50, 61, 75, 65, 9);
  for (let i = 0; i < 100; i++) { m.wallH(i, 0, i, 1, 12); m.wallH(i, 98, i, 99, 12); m.wallH(0, i, 1, i, 12); m.wallH(98, i, 99, i, 12); }

  /* ---------- Декорации ---------- */
  m.span(50, 33, 80, 60, 9.0, 0.6, 'wall');     // крыша над A
  m.span(23, 40, 44, 58, 5.5, 0.5, 'wall');     // крыша лобби
  m.span(44, 38, 49, 44, 4.0, 0.5, 'wall');     // хат
  m.span(29, 59, 48, 80, 4.2, 0.6, 'wall');     // потолок рампы
  m.span(49, 66, 80, 94, 3.2, 0.6, 'wall');     // потолок нижней B
  // «хевен» над A: мостки вдоль стены
  m.box(65, 4.6, 33.8, 30, 0.25, 1.6, 'metal', 0x555b5f);
  m.add('rail', 50, 4.85, 34.6, 80, 4.85, 34.6, 1.0);
  // контейнеры
  m.box(31, 0, 10.5, 6, 2.5, 4, 'container', 0x3f6b3a);
  m.box(31, 2.5, 10.5, 6, 2.5, 2.2, 'container', 0x8a3b2c);
  m.box(41, 0, 22, 2, 2.5, 8, 'container', 0x2f5f9a);
  m.box(55, 0, 7, 6, 2.5, 2, 'container', 0xa8862d);
  m.box(73, 0, 37, 6, 2.5, 2, 'container', 0x3f6b3a);
  m.box(65, -4, 89, 5, 2.5, 2, 'container', 0x8a3b2c);
  // силосы и трубы
  m.add('tank', 64.5, 0, 14.5, 2.6, 9, 0xc9cdd0).add('tank', 64.5, 0, 19.5, 2.2, 7, 0xb9bdc0);
  m.box(50, 7, 3.2, 40, 0.5, 0.5, 'metal', 0x6d7276).box(50, 7.8, 3.2, 40, 0.35, 0.35, 'metal', 0x8a3b2c);
  // окна-проёмы и вентиляционные решётки
  m.winRow('n', 31, 8, 44, 5.5, 6, 1.6, 0.9, 0);
  m.winRow('s', 3, 6, 72, 6.5, 8, 1.8, 0.9, 0);
  m.winRow('w', 97, 6, 66, 5.0, 8, 1.6, 0.9, 0);
  // фонари и кабели
  for (const [x, z] of [[24, 6], [46, 29], [72, 26], [88, 14], [12, 70], [90, 66]]) m.add('lamp', x + 0.5, m.fl(x, z), z + 0.5);
  m.add('wire', 4, 9, 20, 30, 9, 20).add('wire', 74, 10, 8, 96, 10, 8);
  for (const [x, z] of [[5, 35], [22, 71], [43, 57], [79, 34], [95, 5], [60, 29]]) { m.add('barrel', x + 0.5, m.fl(x, z), z + 0.5); m.solid(x, z, x, z, 'o'); }
  // надписи
  m.sign(44, 45, 'n', 'A →', 2.4);
  m.sign(28, 58, 's', '↓ B', 3.2);
  m.sign(80, 65, 'n', 'B ↓', 2.0, 0.5);
  return m;
};
