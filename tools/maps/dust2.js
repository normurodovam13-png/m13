'use strict';
// Dust II. Север — верх радара (z = 0). T-спавн внизу, A справа сверху, B слева сверху.
const { MapBuilder } = require('../lib');

module.exports = function dust2() {
  const m = new MapBuilder('dust2', 2002);

  /* ---------- T-спавн и выходы ---------- */
  m.floor(40, 82, 66, 95, 2);
  m.spawn('T', 45, 88, 61, 93);
  // к туннелям (запад), спуск к «outside tunnels»
  m.ramp(27, 84, 39, 91, 'x', 0.5, 2);
  m.floor(14, 80, 30, 94, 0.5);
  // к лонгу (восток)
  m.ramp(67, 80, 75, 89, 'x', 2, 1);
  m.floor(70, 66, 92, 80, 1);
  // верхний мид: спуск от спавна к миду
  m.ramp(46, 66, 54, 81, 'z', 0, 2);

  /* ---------- Мид ---------- */
  m.floor(42, 36, 54, 65, 0);
  // двери на миде (стена с проёмом)
  m.wall(42, 34, 54, 35, 7.5).floor(45, 34, 49, 35, 0);
  // CT-мид
  m.floor(42, 22, 52, 33, 0.5);             // от дверей мида на север
  m.floor(36, 22, 52, 26, 0.5);             // изгиб на запад: прямой прострел с T до CT-спавна закрыт зданием
  m.floor(36, 15, 40, 21, 0.5);             // и на север к CT-спавну
  m.ramp(42, 30, 52, 33, 'z', 0.5, 0);
  m.crate(52, 44, 53, 45, true);          // xbox
  m.crate(43, 60, 44, 61, false);

  /* ---------- Кэтвок и шорт ---------- */
  m.ramp(55, 47, 59, 53, 'z', 2.5, 0);    // лестница с мида на кэт
  m.floor(55, 18, 60, 46, 2.5);
  m.wall(54, 36, 54, 46, 3.4);            // парапет между кэтом и мидом (запрыгнуть с xbox можно)
  m.floor(61, 18, 66, 26, 2.5);           // шорт к A

  /* ---------- A ---------- */
  m.floor(62, 4, 89, 24, 2.5);
  m.site('A', 62, 4, 89, 24);
  m.wall(62, 13, 64, 17, 7);              // угол между CT-рампой и шортом
  m.crate(74, 11, 75, 12, true).crate(76, 11, 76, 11, false); // дефолт-ящик
  m.crate(86, 5, 88, 7, true);            // «гусь»
  m.crate(67, 7, 68, 7, false);
  m.crate(81, 16, 82, 17, true);
  // рампа с лонга на A
  m.ramp(84, 25, 92, 34, 'z', 2.5, 0.5);
  m.floor(84, 22, 92, 24, 2.5);
  // яма
  m.floor(93, 22, 97, 33, -1);
  m.ramp(93, 34, 97, 37, 'z', -1, 0.5);

  /* ---------- Лонг ---------- */
  m.floor(86, 35, 96, 58, 0.5);
  m.solid(88, 44, 89, 49, 'Q');           // синий контейнер
  m.crate(95, 52, 96, 53, true);
  m.floor(87, 59, 91, 66, 1);             // проход у длинных дверей
  m.ramp(87, 57, 91, 60, 'z', 0.5, 1);
  m.wall(84, 62, 86, 63, 7.5).wall(92, 62, 94, 63, 7.5);

  /* ---------- CT-спавн и рампа к A ---------- */
  m.floor(36, 3, 57, 14, 0.5);
  m.spawn('CT', 41, 5, 55, 11);
  m.ramp(58, 4, 63, 12, 'x', 0.5, 2.5);

  /* ---------- B ---------- */
  m.floor(4, 4, 30, 33, 0.5);
  m.site('B', 4, 4, 30, 33);
  m.floor(4, 4, 9, 9, 1.5);               // задний плат
  m.ramp(4, 10, 9, 12, 'z', 1.5, 0.5);
  m.crate(16, 15, 17, 16, true).crate(18, 15, 18, 15, false); // дефолт B
  m.crate(5, 20, 6, 22, true);            // «бэк-сайт»
  m.crate(20, 29, 21, 31, true);          // ящики у выхода туннелей
  m.crate(12, 26, 12, 27, false);
  m.solid(22, 22, 25, 23, 'q');           // машина на B
  // двери B и коридор к CT-миду
  m.floor(31, 16, 41, 23, 0.5);
  m.wall(31, 16, 32, 16, 7).wall(31, 23, 32, 23, 7);

  /* ---------- Туннели ---------- */
  m.floor(12, 58, 17, 79, 0.5);           // верхние туннели
  m.floor(12, 50, 29, 57, 0);             // развилка
  m.ramp(12, 50, 17, 58, 'z', 0, 0.5);
  m.floor(12, 34, 18, 49, 0.5);           // выход на B
  m.ramp(30, 52, 33, 57, 'x', 0, -1);     // нижние туннели: спуск
  m.floor(34, 52, 39, 57, -1);
  m.ramp(40, 52, 41, 57, 'x', -1, -0.5).ramp(41, 52, 41, 57, 'x', -0.5, -0.5);

  // внешние стены выше
  for (let i = 0; i < 100; i++) { m.wallH(i, 0, i, 1, 10); m.wallH(i, 98, i, 99, 10); m.wallH(0, i, 1, i, 10); m.wallH(98, i, 99, i, 10); }

  /* ---------- Декорации ---------- */
  // Двустворчатые двери на петлях. (x, z) — середина проёма, axis — вдоль какой оси идёт проём,
  // w — ширина проёма, a — угол открытия (0 — закрыты), створки открываются в сторону +z (или +x).
  const door = (x, z, axis, w, a) => {
    const lw = w / 2 - 0.05, y = m.fl(Math.floor(x), Math.floor(z));
    const leaf = (hx, hz, dx, dz, ry) => m.box(hx + dx * lw / 2, y, hz + dz * lw / 2, lw, 2.9, 0.12, 'wood', 0, ry);
    if (axis === 'x') { leaf(x - w / 2, z, Math.cos(a), Math.sin(a), -a); leaf(x + w / 2, z, -Math.cos(a), Math.sin(a), Math.PI + a); }
    else { leaf(x, z - w / 2, Math.sin(a), Math.cos(a), a - Math.PI / 2); leaf(x, z + w / 2, Math.sin(a), -Math.cos(a), Math.PI / 2 - a); }
  };
  // длинные двери
  m.span(87, 62, 91, 63, 4.1, 3.4, 'wall'); door(89.5, 64, 'x', 5, 1.1);
  // двери мида
  m.span(45, 34, 49, 35, 3.2, 4.3, 'wall'); door(47.5, 36, 'x', 5, 1.35);
  // двери B
  m.span(31, 17, 32, 22, 3.3, 3.7, 'wall'); door(33, 20, 'z', 6, 1.2);
  // крыши туннелей
  m.span(11, 60, 18, 79, 3.9, 0.5, 'wall');
  m.span(11, 38, 19, 47, 3.9, 0.5, 'wall');
  m.span(30, 51, 41, 58, 2.4, 0.5, 'wall');
  // арки
  m.span(12, 48, 18, 49, 3.6, 3, 'wall');
  m.span(12, 80, 17, 81, 3.6, 3, 'wall');
  m.span(46, 80, 54, 81, 4.6, 2.4, 'wall');
  // перила на кэтвоке
  m.add('rail', 92.95, 2.5, 22, 92.95, 2.5, 25, 1.0); // над ямой
  // синий контейнер на лонге
  m.box(89, 0.5, 47, 2, 2.1, 6, 'container', 0x2f5f9a);
  // машина на B и на выезде с лонга
  m.add('car', 23.7, 0.5, 23, Math.PI / 2, 0x8a3b2c);
  m.add('car', 78, 1, 74, 0.2, 0xc9b98f);
  m.solid(76, 73, 79, 74, 'q');
  // пальмы
  for (const [x, z, y] of [[42, 84, 2], [64, 94, 2], [37, 5, 0.5], [57, 13, 0.5], [71, 68, 1], [5, 30, 0.5], [88, 22, 2.5]]) m.add('palm', x, y, z, 5 + (x % 3));
  for (const [x, z] of [[42, 84], [64, 94], [37, 5], [57, 13], [71, 68], [5, 30], [88, 22]]) m.solid(x, z, x, z, 'O');
  // бочки
  for (const [x, z] of [[41, 94], [66, 82], [14, 93], [92, 78], [55, 64], [30, 33], [96, 57], [51, 26], [29, 4]]) { m.add('barrel', x + 0.5, m.fl(x, z), z + 0.5); m.solid(x, z, x, z, 'o'); }
  // навесы над стенами
  m.awning(42, 81, 's', 4.4, 5, 1.6, 0xb5452f);
  m.awning(60, 81, 's', 4.4, 5, 1.6, 0x2f6fa5);
  m.awning(41, 40, 'e', 3.2, 4, 1.4, 0xc78f2d);
  m.awning(97, 45, 'w', 3.0, 5, 1.5, 0x6a8d3c);
  m.awning(3, 18, 'e', 3.4, 4, 1.4, 0x8c4a7a);
  // окна
  m.winRow('n', 96, 42, 64, 4.6, 4, 1.1, 1.4, 0x3d6e8e);
  m.winRow('s', 2, 38, 56, 3.6, 4, 1.1, 1.4, 0x6b4a2b);
  m.winRow('e', 85, 37, 56, 3.8, 5, 1.0, 1.3, 0x3d6e8e);
  m.winRow('e', 3, 13, 31, 3.6, 5, 1.0, 1.3, 0x7a5a2b);
  m.winRow('w', 55, 55, 64, 3.0, 4, 1.0, 1.2, 0);
  m.winRow('n', 81, 77, 91, 3.8, 5, 1.0, 1.3, 0x2f6fa5);
  // провода
  m.add('wire', 42, 7.5, 50, 55, 7.5, 50);
  m.add('wire', 86, 7.5, 40, 97, 7.5, 40);
  m.add('wire', 40, 8.5, 86, 66, 8.5, 86);
  // фонари
  for (const [x, z] of [[38, 18], [36, 13], [67, 24], [72, 79], [15, 82]]) m.add('lamp', x + 0.5, m.fl(x, z), z + 0.5);
  // надписи
  m.sign(86, 60, 'e', 'A ↑', 2.6);
  m.sign(52, 35, 's', '↑ CT', 3.0);
  m.sign(22, 49, 's', '← B', 2.4);
  m.sign(63, 27, 'n', 'A →', 3.6);
  m.sign(41, 59, 'e', '← B', 2.0);
  return m;
};
